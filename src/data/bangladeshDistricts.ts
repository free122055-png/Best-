export function findDistrictByName(name: string): DistrictInfo | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();
  return BANGLADESH_DISTRICTS.find(d => 
    d.nameBn === name || 
    d.nameEn.toLowerCase() === clean || 
    clean.includes(d.nameEn.toLowerCase()) || 
    name.includes(d.nameBn)
  );
}
